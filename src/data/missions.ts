export function missionStars(missionId: string, score: number, maxScore: number, mistakes: number): number {
  const ratio = maxScore > 0 ? score / maxScore : 0
  if (mistakes === 0 && ratio >= 0.9) return 3
  if (mistakes <= 1 && ratio >= 0.65) return 2
  return 1
}
